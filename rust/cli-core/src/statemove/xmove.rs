//! `_tfsp_xmove.<key>.hcl` cross-state move manifests, colocated in the
//! destination stack: pull the pairs' source addresses out of `source_stack`'s
//! state and into this one.

use std::fmt::Write;

use super::Move;
use crate::gofmt::quote;
use crate::hclx::{self, Decoder};

const XMOVE_PREFIX: &str = "_tfsp_xmove.";
const XMOVE_SUFFIX: &str = ".hcl";
const XMOVE_BANNER: &str = "# Generated by `tfstackplan state move --via mv` — do not edit by hand. Executed by `tfstackplan state apply`.";
const KEY_PREFIX: &str = "# tfstackplan:key=";

/// A cross-state move manifest.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct XMove {
    /// The stack the resources leave (relative to the `--dir` the manifest was made with).
    pub source_stack: String,
    /// The declared pairs, sorted by `from` once parsed.
    pub pairs: Vec<Move>,
}

/// The manifest file name for a key: `_tfsp_xmove.<key>.hcl`.
pub fn xmove_file_name(key: &str) -> String {
    format!("{XMOVE_PREFIX}{key}{XMOVE_SUFFIX}")
}

/// The key in a manifest file name, or `None` if the name is not a manifest's.
pub fn xmove_key_from_file(name: &str) -> Option<&str> {
    let k = name
        .strip_prefix(XMOVE_PREFIX)?
        .strip_suffix(XMOVE_SUFFIX)?;
    (!k.is_empty()).then_some(k)
}

/// Renders a manifest (Go's `RenderXMove`).
pub fn render_xmove(key: &str, xm: &XMove) -> String {
    let mut b = String::new();
    b.push_str(XMOVE_BANNER);
    b.push('\n');
    let _ = write!(b, "{KEY_PREFIX}{key}\n\n");
    b.push_str("xmove {\n");
    let _ = writeln!(b, "  source_stack = {}", quote(&xm.source_stack));
    b.push_str("  moves = {\n");
    for m in &xm.pairs {
        let _ = writeln!(b, "    {} = {}", quote(&m.from), quote(&m.to));
    }
    b.push_str("  }\n}\n");
    b
}

/// Parses a manifest into its header key (empty when the header is absent) and
/// its move. Pairs come back sorted by `from`, as Go reads them out of a map.
pub fn parse_xmove(content: &str) -> Result<(String, XMove), String> {
    let mut key = String::new();
    for ln in content.split('\n') {
        if let Some(k) = ln.strip_prefix(KEY_PREFIX) {
            key = k.trim().to_string();
        }
    }
    let body = hclx::parse(content).map_err(|e| format!("parse xmove: {e}"))?;
    let decode = |e: String| format!("decode xmove: {e}");
    let mut d = Decoder::new(&body);
    let blocks = d.blocks("xmove");
    d.finish().map_err(decode)?;
    if blocks.len() > 1 {
        return Err(decode(
            "Duplicate xmove block; Only one xmove block is allowed.".to_string(),
        ));
    }
    let Some(blk) = blocks.first() else {
        return Err("xmove manifest has no xmove block".to_string());
    };
    let mut x = Decoder::new(&blk.body);
    let source_stack = x.req_str("source_stack").map_err(decode)?;
    let moves = x
        .opt_string_map("moves")
        .map_err(decode)?
        .ok_or_else(|| {
            decode(
                "Missing required argument; The argument \"moves\" is required, but no definition was found."
                    .to_string(),
            )
        })?;
    x.finish().map_err(decode)?;
    Ok((
        key,
        XMove {
            source_stack,
            pairs: moves.iter().map(|(f, t)| Move::new(f, t)).collect(),
        },
    ))
}

