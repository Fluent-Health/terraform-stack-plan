//! `_tfsp_move.<key>.tf` shims: a machine-readable header (banner, key, one
//! tab-separated op per line) followed by native `moved`/`import`/`removed` blocks.

use std::fmt::Write;

use crate::gofmt::quote;

const SHIM_BANNER: &str = "# Generated by `tfstackplan state move` — do not edit by hand.";
const KEY_PREFIX: &str = "# tfstackplan:key=";
const OP_PREFIX: &str = "# tfstackplan:op=";
const SHIM_PREFIX: &str = "_tfsp_move.";
const SHIM_SUFFIX: &str = ".tf";

/// One shim operation: `moved` (from → to), `import` (to + id) or `removed` (from).
#[derive(Clone, Debug, Default, PartialEq, Eq, Hash)]
pub struct Op {
    /// `moved`, `import` or `removed`.
    pub kind: String,
    /// Source address (`moved`, `removed`).
    pub from: String,
    /// Target address (`moved`, `import`).
    pub to: String,
    /// Import id (`import`).
    pub id: String,
}

impl Op {
    /// A `moved` op.
    pub fn moved(from: &str, to: &str) -> Self {
        Self {
            kind: "moved".into(),
            from: from.into(),
            to: to.into(),
            id: String::new(),
        }
    }

    /// An `import` op.
    pub fn import(to: &str, id: &str) -> Self {
        Self {
            kind: "import".into(),
            from: String::new(),
            to: to.into(),
            id: id.into(),
        }
    }

    /// A `removed` op.
    pub fn removed(from: &str) -> Self {
        Self {
            kind: "removed".into(),
            from: from.into(),
            to: String::new(),
            id: String::new(),
        }
    }
}

/// The shim file name for a key: `_tfsp_move.<key>.tf`.
pub fn shim_file_name(key: &str) -> String {
    format!("{SHIM_PREFIX}{key}{SHIM_SUFFIX}")
}

/// The key in a shim file name, or `None` if the name is not a shim's.
pub fn shim_key_from_file(name: &str) -> Option<&str> {
    let k = name.strip_prefix(SHIM_PREFIX)?.strip_suffix(SHIM_SUFFIX)?;
    (!k.is_empty()).then_some(k)
}

/// Renders a shim (Go's `RenderShim`).
pub fn render_shim(key: &str, ops: &[Op]) -> String {
    let mut b = String::new();
    b.push_str(SHIM_BANNER);
    b.push('\n');
    b.push_str(KEY_PREFIX);
    b.push_str(key);
    b.push('\n');
    for o in ops {
        let _ = writeln!(b, "{OP_PREFIX}{}\t{}\t{}\t{}", o.kind, o.from, o.to, o.id);
    }
    for o in ops {
        match o.kind.as_str() {
            "moved" => {
                let _ = write!(
                    b,
                    "\nmoved {{\n  from = {}\n  to   = {}\n}}\n",
                    o.from, o.to
                );
            }
            "import" => {
                let _ = write!(
                    b,
                    "\nimport {{\n  to = {}\n  id = {}\n}}\n",
                    o.to,
                    quote(&o.id)
                );
            }
            "removed" => {
                let _ = write!(
                    b,
                    "\nremoved {{\n  from = {}\n  lifecycle {{\n    destroy = false\n  }}\n}}\n",
                    o.from
                );
            }
            _ => {}
        }
    }
    b
}

/// Reads a shim's header back into its key and ops (Go's `ParseShim`).
pub fn parse_shim(content: &str) -> Result<(String, Vec<Op>), String> {
    let lines: Vec<&str> = content.split('\n').collect();
    if lines.first().map(|l| l.trim()) != Some(SHIM_BANNER) {
        return Err("not a tfstackplan state-move shim".to_string());
    }
    let mut key = String::new();
    let mut ops = Vec::new();
    for ln in &lines {
        if let Some(k) = ln.strip_prefix(KEY_PREFIX) {
            key = k.trim().to_string();
        } else if let Some(rest) = ln.strip_prefix(OP_PREFIX) {
            let f: Vec<&str> = rest.splitn(4, '\t').collect();
            if f.len() != 4 {
                return Err(format!("malformed op line: {}", quote(ln)));
            }
            ops.push(Op {
                kind: f[0].into(),
                from: f[1].into(),
                to: f[2].into(),
                id: f[3].into(),
            });
        }
    }
    if key.is_empty() {
        return Err("shim missing key header".to_string());
    }
    Ok((key, ops))
}

/// `existing` then `add`, de-duplicating whole ops and keeping order.
pub fn merge_ops(existing: &[Op], add: &[Op]) -> Vec<Op> {
    let mut out: Vec<Op> = Vec::with_capacity(existing.len() + add.len());
    for o in existing.iter().chain(add) {
        if !out.contains(o) {
            out.push(o.clone());
        }
    }
    out
}

