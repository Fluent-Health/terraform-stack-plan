package statemove

import (
	"fmt"
	"io/fs"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/hashicorp/hcl/v2/gohcl"
	"github.com/hashicorp/hcl/v2/hclparse"
)

const (
	xmovePrefix = "_tfsp_xmove."
	xmoveSuffix = ".hcl"
	xmoveBanner = "# Generated by `tfstackplan state move --via mv` — do not edit by hand. Executed by `tfstackplan state apply`."
)

// XMove is a cross-state move manifest, colocated in the DESTINATION stack: pull
// the Pairs' source addresses out of SourceStack's state and into this stack's.
type XMove struct {
	SourceStack string
	Pairs       []Move
}

// XMoveFileName is the manifest filename for a key.
func XMoveFileName(key string) string { return xmovePrefix + key + xmoveSuffix }

// RenderXMove renders the HCL manifest (key in a header comment + an xmove block).
func RenderXMove(key string, xm XMove) string {
	var b strings.Builder
	b.WriteString(xmoveBanner + "\n")
	b.WriteString("# tfstackplan:key=" + key + "\n\n")
	b.WriteString("xmove {\n")
	fmt.Fprintf(&b, "  source_stack = %q\n", xm.SourceStack)
	b.WriteString("  moves = {\n")
	for _, m := range xm.Pairs {
		fmt.Fprintf(&b, "    %q = %q\n", m.From, m.To)
	}
	b.WriteString("  }\n}\n")
	return b.String()
}

type xmoveFile struct {
	XMove *struct {
		SourceStack string            `hcl:"source_stack"`
		Moves       map[string]string `hcl:"moves"`
	} `hcl:"xmove,block"`
}

// ParseXMove parses the manifest content into its key + XMove.
func ParseXMove(content string) (key string, xm XMove, err error) {
	for _, ln := range strings.Split(content, "\n") {
		if strings.HasPrefix(ln, "# tfstackplan:key=") {
			key = strings.TrimSpace(strings.TrimPrefix(ln, "# tfstackplan:key="))
		}
	}
	if key == "" {
		return "", XMove{}, fmt.Errorf("xmove manifest missing key header")
	}
	p := hclparse.NewParser()
	f, diags := p.ParseHCL([]byte(content), "xmove.hcl")
	if diags.HasErrors() {
		return "", XMove{}, fmt.Errorf("parse xmove: %s", diags.Error())
	}
	var decoded xmoveFile
	if diags := gohcl.DecodeBody(f.Body, nil, &decoded); diags.HasErrors() {
		return "", XMove{}, fmt.Errorf("decode xmove: %s", diags.Error())
	}
	if decoded.XMove == nil {
		return "", XMove{}, fmt.Errorf("xmove manifest has no xmove block")
	}
	xm.SourceStack = decoded.XMove.SourceStack
	froms := make([]string, 0, len(decoded.XMove.Moves))
	for k := range decoded.XMove.Moves {
		froms = append(froms, k)
	}
	sort.Strings(froms)
	for _, fr := range froms {
		xm.Pairs = append(xm.Pairs, Move{From: fr, To: decoded.XMove.Moves[fr]})
	}
	return key, xm, nil
}

// FoundXMove is a discovered manifest with its location.
type FoundXMove struct {
	Path      string
	DestStack string // dir relative to root (slash form)
	Key       string
	XMove     XMove
}

// DiscoverXMoves walks root for `_tfsp_xmove.*.hcl` manifests.
func DiscoverXMoves(root string) ([]FoundXMove, error) {
	var out []FoundXMove
	err := filepath.WalkDir(root, func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.IsDir() || !strings.HasPrefix(d.Name(), xmovePrefix) || !strings.HasSuffix(d.Name(), xmoveSuffix) {
			return nil
		}
		data, rerr := os.ReadFile(path)
		if rerr != nil {
			return rerr
		}
		key, xm, perr := ParseXMove(string(data))
		if perr != nil {
			return nil
		}
		rel, _ := filepath.Rel(root, filepath.Dir(path))
		out = append(out, FoundXMove{Path: path, DestStack: filepath.ToSlash(rel), Key: key, XMove: xm})
		return nil
	})
	return out, err
}
